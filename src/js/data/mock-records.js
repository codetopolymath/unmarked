function tracks(id, list) {
  return list.map(([title, duration_s, extra], index) => ({
    index,
    title: title ?? undefined,
    duration_s: duration_s ?? undefined,
    audio: { seed: `${id}:${index}`, seconds: duration_s ?? 75 },
    ...extra,
  }))
}

